"""Download and preprocess the UCI Individual Household Electric Power Consumption data.

Usage:
    python make_data.py                # real data (needs internet)
    python make_data.py --synthetic    # DEV ONLY fake series, never use for results

Outputs (folder data/):
    hourly.csv           datetime, load_kw, split   (real data)
    hourly_synthetic.csv                            (only with --synthetic)
    data_dictionary.md
Fixed seed = config.SEED.
"""
import argparse
import io
import os
import urllib.request
import zipfile

import numpy as np
import pandas as pd

from config import SEED

URL = ("https://archive.ics.uci.edu/static/public/235/"
       "individual+household+electric+power+consumption.zip")
OUT = "data"
MAX_GAP_H = 3


def fill_short_gaps(s: pd.Series, max_gap: int = MAX_GAP_H) -> pd.Series:
    """Interpolate only gaps of at most max_gap hours; longer gaps stay NaN."""
    isna = s.isna()
    grp = (isna != isna.shift()).cumsum()
    runlen = isna.groupby(grp).transform("sum") * isna
    filled = s.interpolate(limit_area="inside")
    return s.where(~(isna & (runlen <= max_gap)), filled)


def keep_complete_days(s: pd.Series) -> pd.Series:
    day = s.index.normalize()
    ok = s.notna().groupby(day).transform("all")
    full = s.groupby(day).transform("size") == 24
    return s[ok & full]


def add_split(s: pd.Series) -> pd.DataFrame:
    """Chronological: final 365 days test, 90 days before it validation, rest train."""
    last = s.index.max().normalize()
    test_start = last - pd.Timedelta(days=364)
    val_start = test_start - pd.Timedelta(days=90)
    split = np.where(s.index >= test_start, "test",
                     np.where(s.index >= val_start, "val", "train"))
    df = s.rename("load_kw").to_frame()
    df["split"] = split
    df.index.name = "datetime"
    return df


def real_hourly() -> pd.Series:
    print("Downloading", URL)
    raw = urllib.request.urlopen(URL, timeout=120).read()
    with zipfile.ZipFile(io.BytesIO(raw)) as z:
        name = [n for n in z.namelist() if n.endswith(".txt")][0]
        df = pd.read_csv(z.open(name), sep=";", na_values=["?"],
                         usecols=["Date", "Time", "Global_active_power"],
                         low_memory=False)
    df["datetime"] = pd.to_datetime(df["Date"] + " " + df["Time"],
                                    format="%d/%m/%Y %H:%M:%S")
    s = df.set_index("datetime")["Global_active_power"].astype(float)
    return s.resample("h").mean()  # mean kW over an hour == kWh for that hour


def synthetic_hourly(days: int = 1200) -> pd.Series:
    rng = np.random.default_rng(SEED)
    idx = pd.date_range("2007-01-01", periods=days * 24, freq="h")
    h = idx.hour.values
    base = 0.8 + 0.6 * np.exp(-((h - 7.5) ** 2) / 4) + 1.4 * np.exp(-((h - 19) ** 2) / 6)
    weekend = 1 + 0.15 * (idx.dayofweek.values >= 5)
    winter = 1 + 0.2 * np.cos(2 * np.pi * (idx.dayofyear.values - 15) / 365)
    noise = rng.normal(0, 0.15, len(idx))
    return pd.Series(np.clip(base * weekend * winter + noise, 0.1, None), index=idx)


DICT = """# Data dictionary (P2 Home Energy Planner)

| Column | Where | Real / generated | Description |
|---|---|---|---|
| datetime | data/hourly.csv | real | Hour start timestamp (from UCI Date + Time) |
| load_kw | data/hourly.csv | real | Mean Global_active_power over the hour, kW. Minutes aggregated by mean; gaps <= 3 h linearly interpolated; days with any remaining gap dropped |
| split | data/hourly.csv | generated by rule | train / val / test: final 365 days = test, 90 days before = val, rest = train (chronological) |
| price | config.py | GENERATED (simulated) | Hourly price per kWh, fixed table (cheap night, evening peak) |
| appliance power / duration / window | config.py | GENERATED (simulated) | Washer, dryer, dishwasher, EV, oven profiles |
| power limit, battery size and rate | config.py | GENERATED (simulated) | 5 kW limit, 4 kWh battery, 2 kWh/h |

Real: household electricity use (one house near Paris, 2006-2010, CC BY 4.0).
Everything else, and every cost / saving computed from it, is SIMULATED.
Not used: Voltage, Global_intensity, Global_reactive_power, Sub_metering_1-3.
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--synthetic", action="store_true",
                    help="DEV ONLY: fake data to test the pipeline offline")
    args = ap.parse_args()
    os.makedirs(OUT, exist_ok=True)
    np.random.seed(SEED)

    if args.synthetic:
        print("WARNING: synthetic data. Do NOT report results from this file.")
        s = synthetic_hourly()
        path = os.path.join(OUT, "hourly_synthetic.csv")
    else:
        s = real_hourly()
        path = os.path.join(OUT, "hourly.csv")

    s = keep_complete_days(fill_short_gaps(s))
    df = add_split(s)
    df.to_csv(path)
    with open(os.path.join(OUT, "data_dictionary.md"), "w", encoding="utf-8") as f:
        f.write(DICT)
    print(f"Saved {path}: {len(df)} hourly rows, {len(df)//24} complete days")
    print(df["split"].value_counts().to_string())


if __name__ == "__main__":
    main()
